"""Generator for a dataset with XOR labels and spurious correlation."""

from argparse import Namespace
from dataclasses import dataclass
from typing import Iterator

from loguru import logger
import torch
from torch.utils.data import IterableDataset


@dataclass
class DatasetConfig:
    """Configuration for Dataset class."""

    name: str  # Dataset name
    d: int = 50  # Data dimension
    n: int = 1000  # Number of data
    m: int = 32  # Batch size
    spurious: bool = False  # Whether to generate data with spurious correlation
    lmbda: float | None = None  # Correlation strength in [0, 0.5]; lower is stronger
    seed: int = 42  # Random seed for dataset generation


# pylint: disable=abstract-method # Allow __getitem__ to not be overidden.
class Dataset(IterableDataset):
    """Generator for a dataset with XOR labels and spurious correlation."""

    def __init__(self, config: DatasetConfig) -> None:
        """Initializes a dataset."""
        super().__init__()
        logger.info(config)
        self.name = config.name
        self.config = config

        # Compute the total number of data to be generated (dropping the remainder).
        self.real_n = config.n - (config.n % config.m)
        if self.config.n != self.real_n:
            logger.warning(
                (
                    f"Dropping last {config.n - self.real_n} samples from dataset"
                    f" '{self.name}' to fit batch size {config.m}"
                )
            )

        # Validate lambda configuration.
        if config.spurious and config.lmbda is None:
            raise ValueError(
                (
                    "Please set config.lmbda if config.spurious is True."
                    f" Current value: {config.lmbda}."
                )
            )

    def generate_data(self, rng: torch.Generator) -> tuple[torch.Tensor, torch.Tensor]:
        """Generates a single batch of data and targets."""
        """
        # Generate i.i.d. data on {±1}^d with target XOR(x_1, x_2).
        randints = torch.randint(0, 2, (self.config.m, self.config.d), generator=rng)
        data = (randints * 2 - 1).float()
        targets = -(data[:, 0] * data[:, 1])

        # Design spurious correlation such that x_3 = y with probability 1 - λ.
        if self.config.spurious:
            data[:, 2] = targets
            flip_mask = torch.rand(self.config.m, generator=rng) < self.config.lmbda
            data[flip_mask, 2] *= -1

        """
        # Reverse complexity of spurious feature and core feature
        randints = torch.randint(0, 2, (self.config.m, self.config.d), generator=rng)
        data = (randints * 2 - 1).float()
        targets = -(data[:, 0] * data[:, 1])
        flip_mask = torch.rand(self.config.m, generator=rng) < self.config.lmbda
        targets[flip_mask] *= -1

        data[:, 2] = targets
        flip_mask = torch.rand(self.config.m, generator=rng) < (2*self.config.lmbda)
        data[flip_mask, 2] *= -1

        return data, targets

    def __len__(self) -> int:
        """Returns the number of batches generated by this dataset."""
        return self.real_n // self.config.m

    def __iter__(self) -> Iterator[tuple[torch.Tensor, torch.Tensor]]:
        """Generates batches of data until total_n batches are reached."""
        rng = torch.Generator().manual_seed(self.config.seed)

        for _ in range(len(self)):
            # Generate data on-demand to save on memory
            data, targets = self.generate_data(rng)
            yield data, targets


def make_dataset_configs(args: Namespace) -> dict[str, DatasetConfig]:
    """Constructs common dataset configs using parameters from args."""

    def make_dataset_config(name: str) -> DatasetConfig:
        """Helper function for making dataset config based on name."""
        train = "train" in name
        spurious = "spurious" in name
        return DatasetConfig(
            name=name,
            d=args.d,
            n=args.m * args.steps if train else args.n_test,
            m=args.m,
            seed=args.train_seed if train else args.test_seed,
            spurious=spurious,
            lmbda=args.lmbda if spurious else None,
        )

    return {
        "train_iid": make_dataset_config("train-iid"),
        "train_spurious": make_dataset_config("train-spurious"),
        "test_iid": make_dataset_config("test-iid"),
        "test_spurious": make_dataset_config("test-spurious"),
    }
